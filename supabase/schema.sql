create or replace function private.is_staff() returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.profiles where id=(select auth.uid()) and role in ('manager','coach') and status='active') $$;
revoke all on function private.is_staff() from public;
grant execute on function private.is_staff() to authenticated;

create or replace function private.is_manager() returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.profiles where id=(select auth.uid()) and role='manager' and status='active') $$;
