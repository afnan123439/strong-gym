create or replace function private.handle_new_user() returns trigger language plpgsql security definer set search_path=public as $$
declare selected_plan bigint; selected_gender public.gender_type;
begin
  selected_gender:=case when new.raw_user_meta_data->>'gender'='male' then 'male'::public.gender_type else 'female'::public.gender_type end;
  insert into public.profiles(id,email,full_name,whatsapp_e164,gender)
  values(new.id,new.email,coalesce(nullif(new.raw_user_meta_data->>'full_name',''),'عضو جديد'),nullif(new.raw_user_meta_data->>'whatsapp_e164',''),selected_gender);
  select id into selected_plan from public.membership_plans where code=coalesce(new.raw_user_meta_data->>'requested_plan','monthly') and active limit 1;
  if selected_plan is not null then insert into public.subscriptions(member_id,plan_id) values(new.id,selected_plan); end if;
  return new;
end $$;
revoke all on function private.handle_new_user() from public;
create trigger on_auth_user_created after insert on auth.users for each row execute function private.handle_new_user();

create or replace function private.notify_account_status() returns trigger language plpgsql security definer set search_path=public as $$
begin
  if old.status='pending' and new.status='active' then
    insert into public.notifications(recipient_id,type,title_ar,title_en,body_ar,body_en,related_entity_type,related_entity_id)
    values(new.id,'account_approved','تم قبول حسابك','Account approved','تم قبول الحساب. أكمل الدفع الكاش لتفعيل الاشتراك.','Your account was approved. Complete the cash payment to activate membership.','profile',new.id);
  end if;
  return new;
end $$;
revoke all on function private.notify_account_status() from public;
create trigger on_profile_status_changed after update of status on public.profiles for each row execute function private.notify_account_status();

create or replace function private.activate_cash_subscription(p_subscription uuid,p_amount integer,p_note text default null)
returns void language plpgsql security definer set search_path=public as $$
declare v_duration integer; v_price integer; v_member uuid;
begin
  if not private.is_staff() then raise exception 'not_authorized'; end if;
  select s.member_id,mp.duration_days,mp.price_ils into v_member,v_duration,v_price
  from public.subscriptions s join public.membership_plans mp on mp.id=s.plan_id where s.id=p_subscription for update;
  if v_member is null then raise exception 'subscription_not_found'; end if;
  if p_amount<>v_price then raise exception 'invalid_amount'; end if;
  insert into public.cash_payments(subscription_id,amount_ils,received_by,note) values(p_subscription,p_amount,auth.uid(),p_note);
  update public.subscriptions set starts_on=current_date,ends_on=current_date+(v_duration-1),status='active' where id=p_subscription;
  insert into public.notifications(recipient_id,type,title_ar,title_en,body_ar,body_en,related_entity_type,related_entity_id)
  values(v_member,'payment_confirmed','تم تفعيل اشتراكك','Membership activated','تم تأكيد الدفعة وبدأ اشتراكك اليوم.','Your cash payment was confirmed and your membership starts today.','subscription',p_subscription);
end $$;
revoke all on function private.activate_cash_subscription(uuid,integer,text) from public;
grant execute on function private.activate_cash_subscription(uuid,integer,text) to authenticated;

create or replace function public.activate_cash_subscription(p_subscription uuid,p_amount integer,p_note text default null)
returns void language plpgsql security definer set search_path=public as $$
declare v_duration integer; v_price integer; v_member uuid; v_role public.app_role;
begin
  select role into v_role from public.profiles where id=(select auth.uid());
  if v_role is null or v_role not in ('manager','coach') then raise exception 'not_authorized'; end if;
  select s.member_id,mp.duration_days,mp.price_ils into v_member,v_duration,v_price
  from public.subscriptions s join public.membership_plans mp on mp.id=s.plan_id
  where s.id=p_subscription and s.status='awaiting_payment' for update;
  if v_member is null then raise exception 'subscription_not_found_or_already_paid'; end if;
  if p_amount<>v_price then raise exception 'invalid_amount'; end if;
  insert into public.cash_payments(subscription_id,amount_ils,received_by,note)
  values(p_subscription,p_amount,(select auth.uid()),p_note);
  update public.subscriptions set starts_on=current_date,ends_on=current_date+(v_duration-1),status='active'
  where id=p_subscription;
  insert into public.notifications(recipient_id,type,title_ar,title_en,body_ar,body_en,related_entity_type,related_entity_id)
  values(v_member,'payment_confirmed','تم تفعيل اشتراكك','Membership activated','تم تأكيد الدفعة وبدأ اشتراكك اليوم.','Your cash payment was confirmed and your membership starts today.','subscription',p_subscription);
end $$;
revoke all on function public.activate_cash_subscription(uuid,integer,text) from public;
revoke all on function public.activate_cash_subscription(uuid,integer,text) from anon;
grant execute on function public.activate_cash_subscription(uuid,integer,text) to authenticated;

create or replace function public.update_own_profile(p_full_name text,p_whatsapp text default null)
returns void language plpgsql security definer set search_path=public as $$
begin
  if (select auth.uid()) is null then raise exception 'not_authorized'; end if;
  if length(trim(p_full_name))<2 then raise exception 'invalid_name'; end if;
  update public.profiles set full_name=trim(p_full_name),whatsapp_e164=nullif(trim(p_whatsapp),''),updated_at=now()
  where id=(select auth.uid());
  insert into public.audit_log(actor_id,action,entity_type,entity_id,details_json)
  values((select auth.uid()),'profile_updated','profile',(select auth.uid())::text,jsonb_build_object('fields',array['full_name','whatsapp_e164']));
end $$;
revoke all on function public.update_own_profile(text,text) from public,anon;
grant execute on function public.update_own_profile(text,text) to authenticated;

create or replace function private.create_expiry_notifications() returns integer language plpgsql security definer set search_path=public as $$
declare inserted_count integer;
begin
  update public.subscriptions set status='expired' where status='active' and ends_on<current_date;
  with expiring as (
    select s.id,s.member_id,p.full_name from public.subscriptions s join public.profiles p on p.id=s.member_id where s.status='active' and s.ends_on=current_date
  ), member_notices as (
    insert into public.notifications(recipient_id,type,title_ar,title_en,body_ar,body_en,related_entity_type,related_entity_id)
    select member_id,'subscription_expires_today','اشتراكك ينتهي اليوم','Your membership expires today','يمكنك طلب التجديد من حسابك بعد موافقتك.','You can request renewal after your approval.','subscription',id from expiring on conflict do nothing returning 1
  ), manager_notices as (
    insert into public.notifications(recipient_id,type,title_ar,title_en,body_ar,body_en,related_entity_type,related_entity_id)
    select mgr.id,'subscription_expires_today','اشتراك ينتهي اليوم','Membership expires today','ينتهي اشتراك '||e.full_name||' اليوم.','The membership for '||e.full_name||' expires today.','subscription',e.id
    from expiring e cross join public.profiles mgr where mgr.role='manager' and mgr.status='active' on conflict do nothing returning 1
  ) select (select count(*) from member_notices)+(select count(*) from manager_notices) into inserted_count;
  return inserted_count;
end $$;
revoke all on function private.create_expiry_notifications() from public;
select cron.schedule('strong-gym-expiry-notifications','0 * * * *',$$select private.create_expiry_notifications();$$);

