-- Workout tracking and adaptive progression
create table if not exists public.workout_logs (
  id uuid primary key default gen_random_uuid(),
  member_id uuid not null references public.profiles(id) on delete cascade,
  program_id uuid not null references public.member_programs(id) on delete cascade,
  session_date date not null default current_date,
  day_index integer not null check (day_index between 0 and 6),
  exercise_name text not null check (char_length(exercise_name) between 2 and 160),
  exercise_type text not null check (exercise_type in ('strength','cardio','mobility')),
  target_text text,
  weight_kg numeric(6,2) check (weight_kg is null or weight_kg between 0 and 500),
  reps integer check (reps is null or reps between 0 and 1000),
  duration_minutes integer check (duration_minutes is null or duration_minutes between 0 and 600),
  difficulty text check (difficulty is null or difficulty in ('easy','good','hard')),
  completed boolean not null default false,
  notes text check (notes is null or char_length(notes) <= 500),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  unique(member_id,program_id,session_date,day_index,exercise_name)
);
create index if not exists idx_workout_logs_member_date on public.workout_logs(member_id,session_date desc);
create index if not exists idx_workout_logs_program_day on public.workout_logs(program_id,day_index,exercise_name,session_date desc);
alter table public.workout_logs enable row level security;
create policy "workout logs readable" on public.workout_logs for select to authenticated using(member_id=(select auth.uid()) or private.is_staff());
create policy "members insert workout logs" on public.workout_logs for insert to authenticated with check(member_id=(select auth.uid()));
create policy "members update workout logs" on public.workout_logs for update to authenticated using(member_id=(select auth.uid())) with check(member_id=(select auth.uid()));
grant select,insert,update on public.workout_logs to authenticated;

