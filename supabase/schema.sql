create schema if not exists private;
create extension if not exists pg_cron with schema pg_catalog;

create type public.app_role as enum ('manager','coach','member');
create type public.account_status as enum ('pending','active','blocked','rejected');
create type public.gender_type as enum ('female','male');
create type public.subscription_status as enum ('awaiting_payment','active','expired','cancelled');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null, full_name text not null, whatsapp_e164 text,
  gender public.gender_type not null,
  role public.app_role not null default 'member',
  status public.account_status not null default 'pending',
  language text not null default 'ar' check (language in ('ar','en')),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table public.membership_plans (
  id bigint generated by default as identity primary key,
  code text not null unique check (code in ('daily','monthly','quarterly')),
  name_ar text not null, name_en text not null,
  price_ils integer not null check (price_ils > 0),
  duration_days integer not null check (duration_days > 0), active boolean not null default true
);

create table public.subscriptions (
  id uuid primary key default gen_random_uuid(), member_id uuid not null references public.profiles(id) on delete cascade,
  plan_id bigint not null references public.membership_plans(id), starts_on date, ends_on date,
  status public.subscription_status not null default 'awaiting_payment', renewal_approved boolean not null default false,
  created_at timestamptz not null default now(),
  constraint subscription_dates_valid check (ends_on is null or starts_on is null or ends_on >= starts_on)
);

create table public.cash_payments (
  id uuid primary key default gen_random_uuid(), subscription_id uuid not null references public.subscriptions(id),
  amount_ils integer not null check (amount_ils > 0), received_by uuid not null references public.profiles(id),
  paid_at timestamptz not null default now(), note text
);

create table public.measurements (
  id uuid primary key default gen_random_uuid(), member_id uuid not null references public.profiles(id) on delete cascade,
  recorded_by uuid not null references public.profiles(id), height_cm numeric(5,2) not null check (height_cm between 50 and 260),
  weight_kg numeric(5,2) not null check (weight_kg between 20 and 400), waist_cm numeric(5,2), chest_cm numeric(5,2),
  hips_cm numeric(5,2), arm_cm numeric(5,2), thigh_cm numeric(5,2), recorded_at timestamptz not null default now()
);

create table public.health_profiles (
  member_id uuid primary key references public.profiles(id) on delete cascade,
  birth_date date, activity_level text, goal text, medical_notes text, updated_at timestamptz not null default now()
);

create table public.notifications (
  id uuid primary key default gen_random_uuid(), recipient_id uuid not null references public.profiles(id) on delete cascade,
  type text not null check (type in ('subscription_expires_today','subscription_expiring','payment_confirmed','account_approved','coach_message')),
  title_ar text not null, title_en text not null, body_ar text not null, body_en text not null,
  related_entity_type text, related_entity_id uuid, read_at timestamptz, created_at timestamptz not null default now()
);

create table public.audit_log (
  id bigint generated by default as identity primary key, actor_id uuid references public.profiles(id),
  action text not null, entity_type text not null, entity_id text, details_json jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table public.member_programs (
  id uuid primary key default gen_random_uuid(), member_id uuid not null references public.profiles(id) on delete cascade,
  created_by uuid not null references public.profiles(id), goal text not null check (goal in ('weight_loss','muscle_gain','fitness')),
  training_days integer not null check (training_days between 2 and 6), daily_calories integer not null check (daily_calories between 1000 and 5000),
  protein_g integer not null check (protein_g between 40 and 400), carbs_g integer not null check (carbs_g between 50 and 700),
  fats_g integer not null check (fats_g between 20 and 250), water_liters numeric(3,1) not null check (water_liters between 1 and 8),
  workout_plan jsonb not null default '[]'::jsonb, meal_plan jsonb not null default '[]'::jsonb,
  notes text, active boolean not null default true, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

